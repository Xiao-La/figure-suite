#!/usr/bin/env python3
"""Build the single-file Obsidian plugin from src/.

All src/ files are plain scripts sharing one module scope, concatenated in
ORDER. The engine (font … templates, edit) has no Obsidian dependency and is
loaded directly by the Node tests in tests/.

src/fontdata.js (the subset fonts, base64) is regenerated by
tools/subset-fonts.js when the fonts in fonts/ change.

Run from this directory:  python3 build.py
"""

import os
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")

HEADER = """/*
 * Figure Suite — generated bundle. Edit files in src/ and run build.py.
 */

const {
  Plugin,
  Modal,
  FuzzySuggestModal,
  Notice,
  MarkdownView,
  TFile,
  PluginSettingTab,
  Setting,
  setIcon,
  normalizePath,
  getLinkpath,
} = require('obsidian');

"""

ORDER = [
    "fontdata.js", "font.js", "mathtext.js", "svg.js", "parse.js", "blocks.js", "tree.js",
    "graph.js", "links.js", "plot.js", "seq.js", "timeline.js", "sets.js", "compose.js", "edit.js", "templates.js", "help.js", "export.js", "panel.js", "main.js",
]


def main():
    node = shutil.which("node")
    fonts = [os.path.join(HERE, "fonts", f"cm-{n}.ttf") for n in ("regular", "italic", "bold")]
    target = os.path.join(SRC, "fontdata.js")
    if node and (not os.path.exists(target) or any(os.path.getmtime(f) > os.path.getmtime(target) for f in fonts)):
        subprocess.run([node, os.path.join(HERE, "tools", "subset-fonts.js")], check=True)
    parts = [HEADER]
    for name in ORDER:
        with open(os.path.join(SRC, name), encoding="utf-8") as handle:
            parts.append(handle.read().rstrip() + "\n\n")
    with open(os.path.join(HERE, "main.js"), "w", encoding="utf-8") as handle:
        handle.write("".join(parts))
    shutil.copyfile(os.path.join(SRC, "styles.css"), os.path.join(HERE, "styles.css"))
    if node:
        subprocess.run([node, "--check", os.path.join(HERE, "main.js")], check=True)
    print("built main.js and styles.css")


if __name__ == "__main__":
    main()
